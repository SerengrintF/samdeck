function stripZhNoise(raw: string): string {
  return raw.trim().replace(/\?/g, '').replace(/\s+/g, ' ')
}

/** 중국어 병법명 → 한국어. 없으면 null */
export function zhDoctrineToKo(raw: string): string | null {
  const t = stripZhNoise(raw)
  if (!t) return null
  return ZH_KO_DOCTRINES[t] ?? ZH_KO_DOCTRINES[t.replace(/\s/g, '')] ?? null
}
